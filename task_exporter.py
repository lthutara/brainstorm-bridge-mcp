"""
Universal Task Exporter for BrainstormBridge.
Converts extracted roadmap items from AI discussions into:
1. Markdown Roadmaps (ROADMAP.md or TASKS.md)
2. JSON files (compatible with Linear, GitHub Issues, Jira)
3. Direct MyPlanner database tasks (optional)
"""

import os
import json
from datetime import datetime
from typing import List, Dict, Any, Optional

def export_tasks_to_markdown(
    action_items: List[Dict[str, Any]],
    title: str = "Project Roadmap",
    source_name: str = "Brainstorm Export",
    output_path: str = "ROADMAP.md"
) -> Dict[str, Any]:
    """
    Format extracted tasks into a clean GitHub Flavored Markdown checklist.
    """
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M")
    lines = [
        f"# {title}",
        f"> Generated by **BrainstormBridge** from `{source_name}` on {now_str}.\n",
        "## Action Items & Milestones\n"
    ]

    p1_tasks = [t for t in action_items if "P1" in t.get("priority", "")]
    p2_tasks = [t for t in action_items if "P2" in t.get("priority", "")]
    p3_tasks = [t for t in action_items if "P3" in t.get("priority", "") or not ("P1" in t.get("priority", "") or "P2" in t.get("priority", ""))]

    if p1_tasks:
        lines.append("### 🔴 Priority 1 (Immediate / Core Architecture)")
        for t in p1_tasks:
            lines.append(f"- [ ] **{t['title']}**")
            if t.get("description") and len(t["description"]) > 10 and t["description"] != t["title"]:
                lines.append(f"  - *Details:* {t['description']}")
        lines.append("")

    if p2_tasks:
        lines.append("### 🟡 Priority 2 (Key Features & Implementation)")
        for t in p2_tasks:
            lines.append(f"- [ ] **{t['title']}**")
            if t.get("description") and len(t["description"]) > 10 and t["description"] != t["title"]:
                lines.append(f"  - *Details:* {t['description']}")
        lines.append("")

    if p3_tasks:
        lines.append("### 🟢 Priority 3 (Refinements & Backlog)")
        for t in p3_tasks:
            lines.append(f"- [ ] **{t['title']}**")
            if t.get("description") and len(t["description"]) > 10 and t["description"] != t["title"]:
                lines.append(f"  - *Details:* {t['description']}")
        lines.append("")

    content = "\n".join(lines)

    try:
        abs_output = os.path.abspath(output_path)
        os.makedirs(os.path.dirname(abs_output), exist_ok=True)
        with open(abs_output, "w", encoding="utf-8") as f:
            f.write(content)
        return {
            "success": True,
            "format": "markdown",
            "file_path": abs_output,
            "task_count": len(action_items),
            "preview": content[:400] + ("..." if len(content) > 400 else "")
        }
    except Exception as e:
        return {"error": f"Failed to write markdown file: {e}"}


def export_tasks_to_json(
    action_items: List[Dict[str, Any]],
    title: str = "Project Roadmap",
    source_name: str = "Brainstorm Export",
    output_path: str = "tasks.json"
) -> Dict[str, Any]:
    """
    Format extracted tasks into structured JSON format.
    """
    payload = {
        "title": title,
        "source": source_name,
        "generated_at": datetime.now().isoformat(),
        "total_tasks": len(action_items),
        "tasks": action_items
    }

    try:
        abs_output = os.path.abspath(output_path)
        os.makedirs(os.path.dirname(abs_output), exist_ok=True)
        with open(abs_output, "w", encoding="utf-8") as f:
            json.dump(payload, f, indent=2)
        return {
            "success": True,
            "format": "json",
            "file_path": abs_output,
            "task_count": len(action_items)
        }
    except Exception as e:
        return {"error": f"Failed to write JSON file: {e}"}
